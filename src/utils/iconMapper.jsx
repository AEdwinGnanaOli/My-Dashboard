/**
 * Get icon component by name
 * @param {string} iconName - Name of the icon
 * @returns {React.ComponentType} - Icon component or DashboardIcon as fallback
 */
export function getIcon(iconName) {
  return ICON_MAP[iconName] || DashboardIcon;
}

/**
 * Create icon element from name
 * @param {string} iconName - Name of the icon
 * @param {object} props - Props to pass to icon component
 * @returns {React.ReactElement} - Icon element
 */
export function createIconElement(iconName, props = {}) {
  const IconComponent = getIcon(iconName);
  return <IconComponent {...props} />;
}

/**
 * Convert navigation config with string icons to React elements
 * @param {array} navigationConfig - Navigation configuration array
 * @returns {array} - Navigation with icon components
 */
export function mapNavigationIcons(navigationConfig) {
  return navigationConfig.map((item) => {
    if (item.kind === 'header' || item.kind === 'divider') {
      return item;
    }

    const mappedItem = {
      ...item,
      icon: item.icon ? createIconElement(item.icon) : undefined,
    };

    if (item.children) {
      mappedItem.children = mapNavigationIcons(item.children);
    }

    return mappedItem;
  });
}

